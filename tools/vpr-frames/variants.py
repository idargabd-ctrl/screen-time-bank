def q_expr1(expr, ans, hint):
    return (f"Задание 1. Найди значение выражения {expr}.", ans, hint)


def q_expr2(expr, ans, hint):
    return (f"Задание 2. Найди значение выражения {expr}.", ans, hint)


def q_route(frm, to, path1, path2, ans):
    return (f"Задание 3. Из {frm} в {to} два пути: {path1} и {path2}. На сколько километров один путь короче другого?",
            ans, "Сложи каждый путь отдельно, потом найди разницу.")


def q_train(start, end, ans):
    return (f"Задание 4. Поезд вышел в {start} и прибыл на конечную станцию в {end} следующих суток. Сколько часов он был в пути?",
            ans, "Ровно сутки — это 24 часа. Прибавь или отними разницу между временем выхода и прибытия.")


def q_figure(rows, area, perimeter):
    return [
        (f"Задание 5. Фигура на клетчатом поле со стороной клетки 1 см состоит из рядов клеток (сверху вниз): {rows}. Найди её площадь в квадратных сантиметрах.",
         area, "Площадь — просто количество клеток внутри фигуры."),
        ("Задание 5, пункт 2. Найди периметр этой фигуры в сантиметрах.",
         perimeter, "Обойди фигуру по контуру и посчитай стороны клеток. Вырезы тоже считаются."),
    ]


